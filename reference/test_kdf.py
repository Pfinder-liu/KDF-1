"""Public-data regression tests: python3 -m unittest -v test_kdf."""
import contextlib
import copy
import io
import itertools
import json
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import patch

import kdf

PHRASE = 'correct horse battery staple'
SECRET = '000102030405060708090a0b0c0d0e0f'
MK = bytes.fromhex('d926cadd0ae78d32398709deebcb1ba4e74e8991a973f06d5cef6e3a63dde787')
SK = bytes.fromhex('60beb81f4da1e9a96b9f78d26df78ab2203c7a0b702912c22a72268de10a7930')
PASSWORD = 'HtO+f3SK@_5w*VwW6ufM@UzA'


class DerivationTests(unittest.TestCase):
    def test_reference_and_determinism(self):
        for _ in range(2):
            self.assertEqual(kdf.derive(PHRASE, SECRET, 'example.com', 'test'),
                             (MK, SK, PASSWORD))

    def test_historical_independent_user_results(self):
        # These were reported from the original CLI, not generated by this suite.
        cases = [('example.org', 'test', 1, '7jdiRErHxZ4*WfxM54UMk^8%'),
                 ('example.com', 'test2', 1, '_unK2KmBLQ1TJbM=8_W^N4SM'),
                 ('example.com', 'test', 2, 'n9m2YPSPTz26Dgr9Q!TrtnFs')]
        for label, account, revision, password in cases:
            with self.subTest(label=label, account=account, revision=revision):
                self.assertEqual(kdf.encode_password(kdf.site_key(MK, label, account, revision)),
                                 password)

    def test_api_canonicalization(self):
        for label in ['example.com', 'EXAMPLE.COM', ' \tExample.Com\r\n']:
            with self.subTest(label=label):
                self.assertEqual(kdf.site_key(MK, label, ' test\t'), SK)
        self.assertEqual(kdf.derive(PHRASE, SECRET, ' EXAMPLE.COM ', ' test '),
                         (MK, SK, PASSWORD))

    def test_account_case_and_empty_account(self):
        self.assertNotEqual(kdf.site_key(MK, 'a', 'Personal'), kdf.site_key(MK, 'a', 'personal'))
        self.assertEqual(kdf.site_key(MK, 'a'), kdf.site_key(MK, 'a', ' \t'))
        self.assertNotEqual(kdf.site_key(MK, 'a'), kdf.site_key(MK, 'a', 'personal'))

    def test_no_domain_aliasing(self):
        self.assertNotEqual(kdf.site_key(MK, 'example.com'),
                            kdf.site_key(MK, 'www.example.com'))
        for label in ['https://example.com', 'example.com/', 'user@example.com']:
            with self.assertRaises(ValueError):
                kdf.site_key(MK, label)

    def test_delimiter_collision_rejected(self):
        for label, account in [('a|b', 'c'), ('a', 'b|c')]:
            with self.assertRaises(ValueError):
                kdf.site_key(MK, label, account)

    def test_label_bounds(self):
        self.assertEqual(kdf.canonical_label('A' * 128), 'a' * 128)
        self.assertEqual(kdf.canonical_label('A' * 128, account=True), 'A' * 128)
        for label in ['', ' \t', 'a' * 129, 'a b', 'a\nb', '中文', 'é', 'e\u0301',
                      'K', 'Ａ', '\u00a0a', 'a\u200b', 'a\x00', '\ud800', None, 1]:
            with self.subTest(label=repr(label)), self.assertRaises(ValueError):
                kdf.canonical_label(label)
        for account in ['a' * 129, 'a|b', 'user@example.com', '中文', None]:
            with self.assertRaises(ValueError):
                kdf.canonical_label(account, account=True)

    def test_master_phrase_nfc(self):
        rs = bytes.fromhex(SECRET)
        self.assertEqual(kdf.master_key('café 密码', rs), kdf.master_key('cafe\u0301 密码', rs))
        self.assertEqual(kdf.norm('e\u0301'), bytes.fromhex('c3a9'))
        self.assertNotEqual(kdf.norm('Ａ'), kdf.norm('A'))  # no NFKC

    def test_master_phrase_case_and_whitespace_significant(self):
        rs = bytes.fromhex(SECRET)
        for phrase in [' ' + PHRASE, PHRASE + ' ', PHRASE.upper()]:
            self.assertNotEqual(kdf.master_key(phrase, rs), MK)

    def test_bad_master_inputs(self):
        for phrase in ['', None, b'abc', '\ud800']:
            with self.assertRaises(ValueError):
                kdf.master_key(phrase, bytes.fromhex(SECRET))
        for rs in [b'', b'a' * 15, b'a' * 17, SECRET]:
            with self.assertRaises(ValueError):
                kdf.master_key(PHRASE, rs)

    def test_recovery_hex(self):
        self.assertEqual(kdf.parse_secret_hex(' \t' + SECRET.upper()[:16] + '\n' +
                                            SECRET.upper()[16:] + '\r'), bytes.fromhex(SECRET))
        for value in ['', '00' * 15, '00' * 17, '0x' + SECRET, 'g' * 32,
                      '\u00a0' + SECRET, None, bytes.fromhex(SECRET)]:
            with self.subTest(value=repr(value)), self.assertRaises(ValueError):
                kdf.parse_secret_hex(value)

    def test_revision_bounds_and_types(self):
        self.assertEqual(len(kdf.site_key(MK, 'a', revision=2**32-1)), 32)
        for value in [0, -1, 2**32, True, False, 1.0, '1', None]:
            with self.subTest(value=value), self.assertRaises(ValueError):
                kdf.site_key(MK, 'a', revision=value)

    def test_length_bounds_prefix_and_alphabet(self):
        self.assertEqual(kdf.encode_password(SK, 8), PASSWORD[:8])
        result = kdf.encode_password(SK, 1024)
        self.assertEqual(len(result), 1024)
        self.assertEqual(result[:24], PASSWORD)
        self.assertLessEqual(set(result), set(kdf.ALPHABET))
        for value in [0, 7, 1025, -1, True, 8.0, '24', None]:
            with self.subTest(value=value), self.assertRaises(ValueError):
                kdf.encode_password(SK, value)

    def test_rejection_sampling_boundary(self):
        with patch.object(kdf, 'stream', return_value=iter([222, 255, 221, 0, 73, 74, 147, 148, 219, 220])):
            self.assertEqual(kdf.encode_password(SK, 8), '+A+A+A_=')

    def test_counter_blocks(self):
        # Independent construction of exactly the first two block messages.
        import hashlib
        import hmac
        expected = b''.join(hmac.digest(SK, message, hashlib.sha256) for message in [
            b'KDF-1-v1|password-stream|\x00\x00\x00\x00\x00\x00\x00\x00',
            b'KDF-1-v1|password-stream|\x00\x00\x00\x00\x00\x00\x00\x01'])
        self.assertEqual(bytes(itertools.islice(kdf.stream(SK), 64)), expected)

    def test_key_lengths(self):
        for key in [b'', b'a' * 31, b'a' * 33, 'a' * 32]:
            with self.assertRaises(ValueError):
                kdf.site_key(key, 'a')
            with self.assertRaises(ValueError):
                kdf.encode_password(key)

    def test_metadata_rejected_before_argon2(self):
        for kwargs in [dict(label='a|b'), dict(label='a', revision=0),
                       dict(label='a', account='@'), dict(label='a', length=7)]:
            with patch.object(kdf, 'hash_secret_raw') as argon:
                with self.assertRaises(ValueError):
                    kdf.derive(PHRASE, SECRET, **kwargs)
                argon.assert_not_called()


class SelfTestAndCLITests(unittest.TestCase):
    def test_self_test_pass(self):
        with contextlib.redirect_stdout(io.StringIO()) as output:
            self.assertTrue(kdf.self_test())
        self.assertIn('PASS:', output.getvalue())

    def test_corrupt_each_expected_field_and_null(self):
        original = json.loads(kdf.VECTOR_PATH.read_text())
        with tempfile.TemporaryDirectory() as temp:
            path = Path(temp) / 'vectors.json'
            for field in original['expected']:
                for replacement in ['wrong', None]:
                    data = copy.deepcopy(original)
                    data['expected'][field] = replacement
                    path.write_text(json.dumps(data))
                    with contextlib.redirect_stderr(io.StringIO()) as errors:
                        self.assertFalse(kdf.self_test(path))
                    self.assertIn('FAIL:', errors.getvalue())

    def test_missing_malformed_wrong_scheme(self):
        with tempfile.TemporaryDirectory() as temp:
            path = Path(temp) / 'vectors.json'
            with contextlib.redirect_stderr(io.StringIO()):
                self.assertFalse(kdf.self_test(path))
                for value in ['{', 'null', '[]', '{}', '{"scheme":"KDF-1-v2"}']:
                    path.write_text(value)
                    self.assertFalse(kdf.self_test(path))

    def test_subprocess_self_test_and_path_resolution(self):
        script = Path(kdf.__file__).resolve()
        with tempfile.TemporaryDirectory() as temp:
            result = subprocess.run([sys.executable, str(script), '--self-test'],
                                    cwd=temp, capture_output=True, text=True)
        self.assertEqual(result.returncode, 0, result.stderr)
        self.assertIn('PASS:', result.stdout)

    def test_subprocess_corrupt_vector_exits_one(self):
        with tempfile.TemporaryDirectory() as temp:
            script = Path(temp) / 'kdf.py'
            script.write_bytes(Path(kdf.__file__).read_bytes())
            data = json.loads(kdf.VECTOR_PATH.read_text())
            data['expected']['password'] = 'wrong'
            (Path(temp) / 'test_vectors.json').write_text(json.dumps(data))
            result = subprocess.run([sys.executable, str(script), '--self-test'],
                                    capture_output=True, text=True)
        self.assertEqual(result.returncode, 1)
        self.assertIn('FAIL:', result.stderr)
        self.assertNotIn('PASS:', result.stdout)

    def test_cli_and_api_agree(self):
        with patch('getpass.getpass', side_effect=[PHRASE, SECRET]), \
                patch('builtins.input', side_effect=[' EXAMPLE.COM ', ' test ', '001', '024']), \
                contextlib.redirect_stdout(io.StringIO()) as output:
            self.assertEqual(kdf.main([]), 0)
        self.assertIn(PASSWORD, output.getvalue())
        self.assertIn('label=example.com; account=\'test\'; revision=1; length=24', output.getvalue())

    def test_cli_invalid_input_no_password(self):
        with patch('getpass.getpass', side_effect=[PHRASE, SECRET]), \
                patch('builtins.input', return_value='a|b'), \
                contextlib.redirect_stdout(io.StringIO()) as output, \
                contextlib.redirect_stderr(io.StringIO()) as errors:
            self.assertEqual(kdf.main([]), 2)
        self.assertNotIn('Derived password:', output.getvalue())
        self.assertNotIn('a|b', errors.getvalue())

    def test_cli_numeric_grammar(self):
        for value in ['+1', '-1', '１', '١', '1_0', '1.0']:
            with patch('builtins.input', return_value=value), self.assertRaises(ValueError):
                kdf.prompt_int('test', 1)
        with patch('builtins.input', return_value=' \t'):
            self.assertEqual(kdf.prompt_int('test', 24), 24)

    def test_hidden_input_unavailable(self):
        import getpass
        import warnings
        def unavailable(prompt):
            warnings.warn('test', getpass.GetPassWarning)
        with patch('getpass.getpass', side_effect=unavailable), \
                contextlib.redirect_stdout(io.StringIO()), \
                contextlib.redirect_stderr(io.StringIO()):
            self.assertEqual(kdf.main([]), 2)


if __name__ == '__main__':
    unittest.main()
